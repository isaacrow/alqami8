/** Merges the museum's spelling variants of one label (hamza, ta marbuta, extra words). */
export function normaliseLabel(label) {
  const l = label.replace(/\s+/g, ' ').replace(/\s*\/\s*سم$/, '').trim();
  const variants = {
    'إسم الصانع': 'اسم الصانع',
    'أسم الصانع': 'اسم الصانع',
    'إسم الواقف': 'اسم الواقف',
    'قطر الاعلى': 'قطر الأعلى',
    'الإرتفاع': 'الارتفاع',
    'سمك الفوهه': 'سمك الفوهة',
    'جهة الورد': 'جهة الورود',
    'سنة الوقفية': 'سنة الوقف',
    'سنة الاصدار': 'سنة الإصدار',
    'تأريخ الإصدار': 'تاريخ الإصدار',
    'تأريخ الصنع': 'تاريخ الصنع',
    'المواد المستعملة في الصناعة': 'المواد المستعملة في صناعة القطعة',
    'المواد المستعملة في صنع القطعة': 'المواد المستعملة في صناعة القطعة',
    'المواد المصنوعة منها القطعة': 'المواد المستعملة في صناعة القطعة',
  };
  return variants[l] || l;
}

